interface EducationalSlidesProps {
  slides?: EducationalSlide[];
  variant?: "player" | "presenter";
  onComplete?: () => void;
  showControls?: boolean;
}

export function EducationalSlides({
  slides,
  variant = "player",
  onComplete,
  showControls = true,
}: EducationalSlidesProps) {
  const slideSet =
    slides ||
    (variant === "presenter"
      ? PRESENTER_EDUCATIONAL_SLIDES
      : PSBT_EDUCATIONAL_SLIDES);

  const [currentIndex, setCurrentIndex] = useState(0);

  const handleNext = () => {
    if (currentIndex < slideSet.length - 1) {
      setCurrentIndex(currentIndex + 1);
    } else {
      onComplete?.();
    }
  };

  const handlePrev = () => {
    if (currentIndex > 0) {
      setCurrentIndex(currentIndex - 1);
    }
  };

  const currentSlide = slideSet[currentIndex];

  return (
    <div className="w-full max-w-2xl mx-auto">
      {/* Progress dots */}
      <div className="flex justify-center gap-2 mb-6">
        {slideSet.map((slide, i) => (
          <button
            key={slide.id}
            onClick={() => setCurrentIndex(i)}
            className={`w-2 h-2 rounded-full transition-all ${
              i === currentIndex
                ? "bg-neon w-6"
                : i < currentIndex
                  ? "bg-neon/50"
                  : "bg-muted"
            }`}
          />
        ))}
      </div>

      {/* Slide content */}
      <AnimatePresence mode="wait">
        <motion.div
          key={currentSlide.id}
          initial={{ opacity: 0, x: 20 }}
          animate={{ opacity: 1, x: 0 }}
          exit={{ opacity: 0, x: -20 }}
          transition={{ duration: 0.3 }}
          className="bg-card border border-border rounded-lg p-6"
        >
          <h2 className="font-mono text-xl text-neon mb-1">
            {currentSlide.title}
          </h2>
          {currentSlide.subtitle && (
            <p className="font-mono text-sm text-muted-foreground mb-6">
              {currentSlide.subtitle}
            </p>
          )}
          <div className="font-mono text-sm text-foreground leading-relaxed">
            {currentSlide.content}
          </div>
        </motion.div>
      </AnimatePresence>

      {/* Navigation */}
      {showControls && (
        <div className="flex justify-between items-center mt-6">
          <Button
            variant="outline"
            onClick={handlePrev}
            disabled={currentIndex === 0}
            className="font-mono"
          >
            Previous
          </Button>
          <span className="font-mono text-sm text-muted-foreground">
            {currentIndex + 1} / {slideSet.length}
          </span>
          <Button
            onClick={handleNext}
            className="font-mono bg-neon text-background hover:bg-neon/80"
          >
            {currentIndex === slideSet.length - 1 ? "Get Started" : "Next"}
          </Button>
        </div>
      )}
    </div>
  );
}

// Mini educational tooltip
export function EducationalTooltip({
  term,
  explanation,
  children,
}: {
  term: string;
  explanation: string;
  children: React.ReactNode;
}) {
  const [isOpen, setIsOpen] = useState(false);

  return (
    <span className="relative inline-block">
      <span
        onMouseEnter={() => setIsOpen(true)}
        onMouseLeave={() => setIsOpen(false)}
        className="border-b border-dotted border-neon cursor-help"
      >
        {children}
      </span>
      <AnimatePresence>
        {isOpen && (
          <motion.div
            initial={{ opacity: 0, y: 5 }}
            animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0, y: 5 }}
            className="absolute bottom-full left-1/2 -translate-x-1/2 mb-2 w-64 p-3 bg-card border border-border rounded-lg shadow-lg z-50"
          >
            <div className="font-mono text-xs text-neon mb-1">{term}</div>
            <div className="font-mono text-xs text-muted-foreground">
              {explanation}
            </div>
          </motion.div>
        )}
      </AnimatePresence>
    </span>
  );
}
